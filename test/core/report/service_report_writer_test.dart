// SPEC.md §12's document, laid out onto a page — against a recording canvas
// rather than a real one.
//
// The port is the point. A PDF library is a dependency that has to be audited
// for a network path (SPEC.md §2), and the LAYOUT decisions — which rows go on
// which page, where the repeating header goes, which edge the date column sits
// against in Persian — are decisions this app makes, not ones a library makes
// for it. Putting them behind an interface means they can be asserted here, in
// milliseconds, and that swapping the library later cannot silently move them.
@TestOn('vm')
library;

